#!/usr/bin/env python3
"""Convert an 8x16 BDF font into a Rust glyph table for the kernel console.

Usage: bdf2rs.py <font.bdf> <output.rs>

Only fixed 8x16 glyphs are accepted. The output is a sorted array of
(codepoint, [u8; 16]) pairs so the kernel can binary-search it.
"""

import sys

RANGES = [
    (0x20, 0x7E),      # ASCII
    (0xA0, 0xFF),      # Latin-1 supplement
    (0x400, 0x45F),    # Cyrillic
    (0x2500, 0x259F),  # box drawing, block elements
]


def wanted(cp):
    return any(lo <= cp <= hi for lo, hi in RANGES)


def parse(path):
    glyphs = {}
    cp = None
    rows = None
    with open(path, encoding="ascii", errors="replace") as f:
        for line in f:
            parts = line.split()
            if not parts:
                continue
            if parts[0] == "ENCODING":
                cp = int(parts[1])
            elif parts[0] == "BBX":
                if parts[1:3] != ["8", "16"]:
                    cp = None  # skip glyphs that are not full cells
            elif parts[0] == "BITMAP":
                rows = []
            elif parts[0] == "ENDCHAR":
                if cp is not None and rows is not None and len(rows) == 16 and wanted(cp):
                    glyphs[cp] = rows
                cp = None
                rows = None
            elif rows is not None:
                rows.append(int(parts[0], 16))
    return glyphs


def main():
    src, dst = sys.argv[1], sys.argv[2]
    glyphs = parse(src)
    out = []
    out.append("// Generated by tools/fontgen/bdf2rs.py from Spleen 8x16.")
    out.append("// Spleen: Copyright (c) 2018-2026, Frederic Cambus. BSD-2-Clause.")
    out.append("// See docs/third-party.md. Do not edit by hand.")
    out.append("")
    out.append("pub static GLYPHS: [(u32, [u8; 16]); %d] = [" % len(glyphs))
    for cp in sorted(glyphs):
        rows = ", ".join("0x%02x" % r for r in glyphs[cp])
        out.append("    (0x%04x, [%s])," % (cp, rows))
    out.append("];")
    out.append("")
    with open(dst, "w", encoding="ascii", newline="\n") as f:
        f.write("\n".join(out))
    print("%d glyphs written to %s" % (len(glyphs), dst))


if __name__ == "__main__":
    main()
