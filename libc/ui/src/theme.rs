//! Colours of the dark (graphite) and light themes.

use crate::canvas::{Color, rgb, rgba};

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Theme {
    pub dark: bool,
    /// Behind the window.
    pub backdrop: Color,
    pub backdrop_glow: Color,
    pub window: Color,
    pub window_border: Color,
    pub shadow: Color,
    pub sidebar: Color,
    /// Soft wave shapes on the window background.
    pub wave: Color,
    pub text: Color,
    pub text_dim: Color,
    pub text_faint: Color,
    /// Input fields, lists and secondary buttons.
    pub field: Color,
    pub field_hover: Color,
    pub field_border: Color,
    pub selected: Color,
    pub scrollbar: Color,
    /// The main button (a light pill on the dark theme).
    pub primary: Color,
    pub primary_hover: Color,
    pub on_primary: Color,
    pub focus: Color,
    pub track_off: Color,
    pub track_on: Color,
    pub knob: Color,
    pub knob_off: Color,
    pub progress: Color,
    pub progress_track: Color,
}

